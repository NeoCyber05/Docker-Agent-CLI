# --- round-trip a typical event stream ----------------------------------

def test_event_sequence_round_trip() -> None:
    payload = [
        {"type": "iteration_start", "n": 1},
        {"type": "assistant_text", "delta": "ok"},
        {"type": "tool_call", "name": "list_stacks", "input": {}},
        {"type": "tool_progress", "msg": "scanning"},
        {"type": "tool_result", "name": "list_stacks", "output": []},
        {"type": "usage", "inputTokens": 5, "outputTokens": 10},
    ]
    parsed = [loop_adapter.validate_python(p) for p in payload]
    dumped = [m.model_dump(by_alias=True) for m in parsed]
    assert dumped == payload