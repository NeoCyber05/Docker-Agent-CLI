import { Box, Text } from "ink";
import type React from "react";
import { useMemo, useRef, useState } from "react";
import type { PermissionResponse } from "src/types/permissions";
import type { StackDiff } from "src/types/stack";
import { QueryEngine, type QueryEngineDeps } from "../QueryEngine";
import { Footer } from "../components/Footer";
import { Header } from "../components/Header";
import { MessageList, type UIMessage } from "../components/MessageList";
import { PermissionDialog } from "../components/PermissionDialog";
import { PlanPreview } from "../components/PlanPreview";
import { PromptInput } from "../components/PromptInput";
import { SecretsInputDialog } from "../components/SecretsInputDialog";
import { TypedConfirmDialog } from "../components/TypedConfirmDialog";

type Pending =
  | { kind: "permission"; id: string; tool: string; input: unknown }
  | {
      kind: "confirm";
      id: string;
      composeYaml: string;
      diff: StackDiff;
      autoGeneratedSecrets?: Array<{ service: string; keys: string[] }>;
    }
  | { kind: "typed"; id: string; phrase: string; reason: string }
  | { kind: "secrets"; id: string; service: string; keys: string[]; reason: string };

const DESTRUCTIVE_TOOLS = new Set(["apply_stack", "destroy_stack", "destroy_all_stacks"]);

export function REPL({
  deps,
}: { deps: QueryEngineDeps & { providerName: string; yes?: boolean } }): React.ReactElement {
  const engine = useMemo(() => new QueryEngine(deps), [deps]);
  const [messages, setMessages] = useState<UIMessage[]>([]);
  const [pending, setPending] = useState<Pending | null>(null);
  const [streaming, setStreaming] = useState(false);
  const nextKey = useRef(0);
  const mk = (): number => nextKey.current++;

  const handleSubmit = async (input: string) => {
    let targetPrompt = input.trim();
    if (targetPrompt.startsWith("/")) {
      const parts = targetPrompt.split(/\s+/);
      const cmd = parts[0]?.toLowerCase();
      const arg = parts.slice(1).join(" ");

      if (cmd === "/quit" || cmd === "/exit") {
        process.exit(0);
      }
      if (cmd === "/clear") {
        engine.reset();
        setMessages([]);
        nextKey.current = 0;
        return;
      }
      if (cmd === "/help") {
        setMessages((m) => [
          ...m,
          { key: mk(), role: "user", text: input },
          {
            key: mk(),
            role: "assistant",
            text:
              "Các lệnh slash hỗ trợ:\n" +
              "- /help: Hiển thị hướng dẫn này\n" +
              "- /clear: Xóa lịch sử trò chuyện và session\n" +
              "- /quit: Thoát chương trình\n" +
              "- /stacks: Danh sách các stack\n" +
              "- /status <stack>: Trạng thái chi tiết và drift của stack\n" +
              "- /destroy <stack>: Xóa stack\n" +
              "- /destroy all: Xóa toàn bộ stack\n" +
              "- /secrets list <stack>: Danh sách các secret keys\n" +
              "- /secrets rotate <stack> <service>: Xoay vòng secrets dịch vụ\n" +
              "- /provider <name>: Đổi provider (gemini, openai, ollama)\n" +
              "- /yaml <stack>: Xem file cấu hình YAML của stack",
          },
        ]);
        return;
      }
      if (cmd === "/provider") {
        if (!arg) {
          setMessages((m) => [
            ...m,
            { key: mk(), role: "user", text: input },
            { key: mk(), role: "error", text: "Thiếu tên provider. Ví dụ: /provider openai" },
          ]);
          return;
        }
        setMessages((m) => [
          ...m,
          { key: mk(), role: "user", text: input },
          { key: mk(), role: "assistant", text: `Đã đổi provider sang: ${arg}` },
        ]);
        return;
      }

      // Convert other slash commands to natural prompts
      if (cmd === "/stacks") targetPrompt = "Hiển thị danh sách các stack hiện tại dưới dạng bảng";
      else if (cmd === "/status")
        targetPrompt = `Hãy hiển thị trạng thái và kiểm tra drift của stack ${arg}`;
      else if (cmd === "/destroy" && arg === "all") targetPrompt = "Hãy destroy tất cả các stack";
      else if (cmd === "/destroy") targetPrompt = `Hãy destroy stack ${arg}`;
      else if (cmd === "/secrets" && parts[1] === "list")
        targetPrompt = `Hãy liệt kê các secret key của stack ${parts.slice(2).join(" ")}`;
      else if (cmd === "/secrets" && parts[1] === "rotate") {
        const subparts = parts.slice(2);
        targetPrompt = `Hãy rotate secret của dịch vụ ${subparts[1]} trong stack ${subparts[0]}`;
      } else if (cmd === "/yaml") targetPrompt = `Hãy hiển thị file YAML cấu hình của stack ${arg}`;
    }

    setMessages((m) => [...m, { key: mk(), role: "user", text: input }]);
    setStreaming(true);
    try {
      for await (const ev of engine.query(targetPrompt)) {
        switch (ev.type) {
          case "assistant_text":
            setMessages((m) => {
              const last = m[m.length - 1];
              if (last && last.role === "assistant" && last.text !== undefined) {
                return [...m.slice(0, -1), { ...last, text: last.text + ev.delta }];
              }
              return [...m, { key: mk(), role: "assistant", text: ev.delta }];
            });
            break;
          case "tool_call":
            setMessages((m) => [
              ...m,
              { key: mk(), role: "tool", name: ev.name, status: "running" },
            ]);
            break;
          case "tool_progress":
            setMessages((m) => {
              const copy = [...m];
              for (let i = copy.length - 1; i >= 0; i--) {
                const item = copy[i];
                if (item && item.role === "tool") {
                  copy[i] = { ...item, text: ev.msg };
                  break;
                }
              }
              return copy;
            });
            break;
          case "tool_result":
            setMessages((m) => {
              const copy = [...m];
              for (let i = copy.length - 1; i >= 0; i--) {
                const item = copy[i];
                if (item && item.role === "tool" && item.name === ev.name) {
                  copy[i] = { ...item, status: "done" as const };
                  break;
                }
              }
              return copy;
            });
            break;
          case "plan_ready":
            setPending({
              kind: "confirm",
              id: ev.id,
              composeYaml: ev.composeYaml,
              diff: ev.diff,
              ...(ev.autoGeneratedSecrets ? { autoGeneratedSecrets: ev.autoGeneratedSecrets } : {}),
            });
            break;
          case "permission_request":
            if (deps.yes && !DESTRUCTIVE_TOOLS.has(ev.tool)) {
              engine.respondTo(ev.id, { kind: "approve" });
            } else {
              setPending({ kind: "permission", id: ev.id, tool: ev.tool, input: ev.input });
            }
            break;
          case "typed_confirm_request":
            setPending({ kind: "typed", id: ev.id, phrase: ev.phrase, reason: ev.reason });
            break;
          case "secrets_input_request":
            setPending({
              kind: "secrets",
              id: ev.id,
              service: ev.service,
              keys: ev.keys,
              reason: ev.reason,
            });
            break;
          case "usage":
            // engine.totalUsage is automatically updated by QueryEngine
            break;
          case "error":
            setMessages((m) => [...m, { key: mk(), role: "error", text: ev.error.message }]);
            break;
        }
      }
    } finally {
      setStreaming(false);
    }
  };

  const onAnswer = (answer: PermissionResponse) => {
    if (!pending) return;
    engine.respondTo(pending.id, answer);
    setPending(null);
  };

  return (
    <Box flexDirection="column">
      <Header provider={deps.providerName} />
      <MessageList messages={messages} />
      {pending?.kind === "permission" && (
        <PermissionDialog tool={pending.tool} input={pending.input} onAnswer={onAnswer} />
      )}
      {pending?.kind === "confirm" && (
        <PlanPreview
          composeYaml={pending.composeYaml}
          diff={pending.diff}
          {...(pending.autoGeneratedSecrets
            ? { autoGeneratedSecrets: pending.autoGeneratedSecrets }
            : {})}
          onAnswer={onAnswer}
        />
      )}
      {pending?.kind === "typed" && (
        <TypedConfirmDialog phrase={pending.phrase} reason={pending.reason} onAnswer={onAnswer} />
      )}
      {pending?.kind === "secrets" && (
        <SecretsInputDialog
          service={pending.service}
          keys={pending.keys}
          reason={pending.reason}
          onAnswer={onAnswer}
        />
      )}
      {!pending && streaming && (
        <Box paddingLeft={1} marginY={1}>
          <Text color="yellow" italic>
            Thinking...
          </Text>
        </Box>
      )}
      {!pending && !streaming && <PromptInput onSubmit={handleSubmit} />}
      <Footer usage={engine.totalUsage} />
    </Box>
  );
}
